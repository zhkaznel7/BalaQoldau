export function withProgramTranslation<T extends {slug:string;title:string;description:string}>(program: T) {
  const entry = Object.hasOwn(russian, program.slug) ? russian[program.slug] : undefined;
  if (!entry || createHash('sha256').update(JSON.stringify([program.title, program.description])).digest('hex') !== entry.original) return program;
  return {...program, translationRu: {title: entry.title, description: entry.description}};
}
